"""Reversible, experiment-only interventions for the v8 attention adapter.

This module is deliberately outside ``main/src``.  The default installation is
empty, and ``uninstall`` restores every patched function/parameter.  Halo uses
the original window as the query/output extent: only Native Local's K/V read
support grows, and RoPE indices are regenerated by the existing
``native_local`` implementation for the expanded rectangle.
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Any

import torch


@dataclass(frozen=True)
class ExperimentSpec:
    native_halo_cells: int = 0
    native_halo_motion_band: bool = False
    native_anchor_bridge_alpha: float = 0.0
    native_anchor_bridge_query_latents: tuple[int, ...] | list[int] | None = None
    native_anchor_bridge_key_latents: tuple[int, ...] | list[int] | None = None
    native_anchor_bridge_columns: int = 2
    native_local_weight: float | None = None
    local_weight_bias: float | None = None
    reduce_global_to_local_weight: float | None = None
    collect_branch_stats: bool = False

    def validate(self) -> None:
        if self.native_halo_cells not in (0, 1, 2):
            raise ValueError("native_halo_cells must be 0, 1, or 2")
        if self.native_halo_motion_band and not self.native_halo_cells:
            raise ValueError('motion band requires a nonzero halo')
        if not (0.0 <= self.native_anchor_bridge_alpha <= 0.25):
            raise ValueError("native_anchor_bridge_alpha must be in [0, 0.25]")
        if self.native_anchor_bridge_alpha and self.native_halo_cells:
            raise ValueError("Native halo and Anchor bridge cannot be combined")
        bridge_options = (
            self.native_anchor_bridge_query_latents is not None
            or self.native_anchor_bridge_key_latents is not None
            or self.native_anchor_bridge_columns != 2
        )
        if bridge_options and not self.native_anchor_bridge_alpha:
            raise ValueError("Anchor bridge latent/column options require an active bridge alpha")
        if type(self.native_anchor_bridge_columns) is not int or self.native_anchor_bridge_columns < 1:
            raise ValueError("native_anchor_bridge_columns must be a positive integer")
        for name in ("native_anchor_bridge_query_latents", "native_anchor_bridge_key_latents"):
            values = getattr(self, name)
            if values is None:
                continue
            if not isinstance(values, (list, tuple)) or not values:
                raise ValueError(f"{name} must be a nonempty list or tuple")
            if any(type(index) is not int or index < 0 for index in values):
                raise ValueError(f"{name} must contain only nonnegative integer indices")
            if len(set(values)) != len(values) or tuple(sorted(values)) != tuple(values):
                raise ValueError(f"{name} must be unique and increasing")
        for name in ("native_local_weight", "local_weight_bias", "reduce_global_to_local_weight"):
            value = getattr(self, name)
            if value is not None and not (0.0 < value < 1.0):
                raise ValueError(f"{name} must be strictly between 0 and 1")


@dataclass
class InterventionHandle:
    model: Any
    originals: dict[str, Any] = field(default_factory=dict)
    parameters: list[tuple[torch.Tensor, torch.Tensor]] = field(default_factory=list)
    stats: dict[int, dict[str, Any]] = field(default_factory=dict)
    stats_dtype: str = 'float32'
    absolute_start_frame: int = 0
    motion_band: dict[str, Any] = field(default_factory=lambda: {
        "eligible_calls": 0, "expanded_calls": 0, "fallback_calls": 0,
        "start_frames": [], "windows": [], "latent_indices": [1, 2],
    })
    anchor_bridge: dict[str, Any] = field(default_factory=lambda: {
        "calls": 0, "eligible_calls": 0, "fallback_calls": 0,
        "query_counts": [], "added_kv_counts": [], "absolute_starts": [],
        "windows": [], "anchors": [], "alphas": [], "query_latent_sets": [],
        "key_latent_sets": [], "columns": [], "rejections": [],
    })
    hook_handles: list[Any] = field(default_factory=list)
    installed: bool = True

    def uninstall(self) -> None:
        if not self.installed:
            return
        if "native_local" in self.originals:
            import ltx_outpaint.model as model_mod
            model_mod.native_local = self.originals["native_local"]
        if "adaptive_local" in self.originals:
            model_mod.adaptive_local = self.originals["adaptive_local"]
        if "global_attention" in self.originals:
            model_mod.global_attention = self.originals["global_attention"]
        for name, value in self.originals.items():
            if name.startswith("forward:"):
                module = value[0]
                module.forward = value[1]
        with torch.no_grad():
            for parameter, old in self.parameters:
                parameter.copy_(old)
        for hook in self.hook_handles:
            hook.remove()
        self.installed = False


def _logit(p: float) -> float:
    return math.log(p / (1.0 - p))


def install(transformer: Any, experiment_spec: ExperimentSpec | dict[str, Any] | None = None) -> InterventionHandle:
    """Install one reversible intervention set on an already-loaded model.

    No spec (or an all-default spec) is a no-op apart from returning a handle.
    The model is expected to have ``MultiViewSelfAttention`` instances under
    ``*.attn1`` after ``install_outpainting``.
    """
    if experiment_spec is None:
        spec = ExperimentSpec()
    elif isinstance(experiment_spec, dict):
        spec = ExperimentSpec(**experiment_spec)
    else:
        spec = experiment_spec
    spec.validate()
    handle = InterventionHandle(transformer)
    if all(getattr(spec, f.name) in (f.default, None) for f in __import__("dataclasses").fields(spec)):
        return handle

    if spec.native_halo_cells:
        import ltx_outpaint.model as model_mod
        original_native = model_mod.native_local
        handle.originals["native_local"] = original_native

        def halo_native(attention, grid, window, context):
            g = context.geometry
            if spec.native_halo_motion_band:
                # Anchor-observed vehicle enters at the left/lower boundary in
                # the first17f. Later chunks and distant windows use baseline.
                if (handle.absolute_start_frame != 0 or window.x0 >= g.width//4
                        or window.y1 <= g.height//2):
                    handle.motion_band["fallback_calls"] += 1
                    return original_native(attention, grid, window, context)
                handle.motion_band["eligible_calls"] += 1
                handle.motion_band["expanded_calls"] += 1
                if len(handle.motion_band["start_frames"]) < 64:
                    handle.motion_band["start_frames"].append(handle.absolute_start_frame)
                    handle.motion_band["windows"].append([window.y0, window.x0, window.y1, window.x1])
            halo = spec.native_halo_cells
            from ltx_outpaint.geometry import Rect
            expanded = Rect(
                max(0, window.y0 - halo), max(0, window.x0 - halo),
                min(g.height, window.y1 + halo), min(g.width, window.x1 + halo),
            )
            result = original_native(attention, grid, expanded, context)
            cropped = result[:, :, window.y0 - expanded.y0:window.y1 - expanded.y0,
                             window.x0 - expanded.x0:window.x1 - expanded.x0]
            if not spec.native_halo_motion_band:
                return cropped
            baseline = original_native(attention, grid, window, context)
            t = torch.arange(cropped.shape[1], device=cropped.device)[None, :, None, None, None]
            y = torch.arange(window.y0, window.y1, device=cropped.device)[None, None, :, None, None]
            x = torch.arange(window.x0, window.x1, device=cropped.device)[None, None, None, :, None]
            changed = (t >= 1) & (t < 3) & (y >= g.height//2) & (x < g.width//4)
            return torch.where(changed, cropped, baseline)

        model_mod.native_local = halo_native

    if spec.native_anchor_bridge_alpha:
        import ltx_outpaint.model as model_mod
        original_native = model_mod.native_local
        handle.originals["native_local"] = original_native

        def bridge_native(attention, grid, window, context):
            baseline = original_native(attention, grid, window, context)
            if handle.absolute_start_frame != 0:
                handle.anchor_bridge["fallback_calls"] += 1
                return baseline
            # Lazy by design: legacy/default jobs never import the helper.
            from native_anchor_bridge import anchor_bridge_native
            if len(handle.anchor_bridge["absolute_starts"]) < 64:
                handle.anchor_bridge["absolute_starts"].append(handle.absolute_start_frame)
                handle.anchor_bridge["windows"].append(
                    [window.y0, window.x0, window.y1, window.x1])
                handle.anchor_bridge["alphas"].append(spec.native_anchor_bridge_alpha)
                handle.anchor_bridge["query_latent_sets"].append(
                    list(spec.native_anchor_bridge_query_latents)
                    if spec.native_anchor_bridge_query_latents is not None else [1, 2])
                handle.anchor_bridge["key_latent_sets"].append(
                    list(spec.native_anchor_bridge_key_latents)
                    if spec.native_anchor_bridge_key_latents is not None else None)
                handle.anchor_bridge["columns"].append(spec.native_anchor_bridge_columns)
            return anchor_bridge_native(
                attention, grid, window, context, baseline,
                spec.native_anchor_bridge_alpha, handle.anchor_bridge,
                query_latents=spec.native_anchor_bridge_query_latents,
                key_latents=spec.native_anchor_bridge_key_latents,
                columns=spec.native_anchor_bridge_columns,
            )

        model_mod.native_local = bridge_native

    if spec.collect_branch_stats:
        try:
            import ltx_outpaint.model as model_mod
        except ModuleNotFoundError:
            model_mod = None
        if model_mod is None:
            marked = None
        else:
            originals = {name: getattr(model_mod, name) for name in ("native_local", "adaptive_local", "global_attention")}
            for name, original in originals.items():
                # Statistics must call the installed halo, while uninstall
                # restores the function from before either intervention.
                handle.originals.setdefault(name, original)
        marked = next((m for m in transformer.modules() if hasattr(m, "local_fusion") and hasattr(m, "global_fusion")), None)
        if marked is not None and model_mod is not None:
            marked._experiment_stats = handle

        def record(branch, value):
            if not torch.is_tensor(value):
                return value
            # BF16 scalar sums can stop changing after hundreds of windows.
            # Diagnostics reduce and accumulate in FP32; model outputs remain
            # the original tensors and no random state is consumed.
            flat = value.detach().float()
            # Accumulate bounded scalar tensors; no .item()/CPU transfer occurs here.
            scalars = {"sum": flat.mean(), "energy": flat.square().mean(), "count": 1}
            if flat.ndim >= 4:
                scalars["spatial_gradient"] = (flat[..., 1:, :] - flat[..., :-1, :]).abs().mean()
                scalars["temporal_gradient"] = ((flat[:, 1:] - flat[:, :-1]).abs().mean()
                                                  if flat.shape[1] > 1 else flat.new_zeros(()))
            bucket = handle.stats.setdefault(branch, {"sum": None, "energy": None, "spatial_gradient": None, "temporal_gradient": None, "count": 0})
            for key, tensor in scalars.items():
                if key == "count":
                    continue
                bucket[key] = tensor if bucket[key] is None else bucket[key] + tensor
            bucket["count"] += 1
            return value

        def native_capture(attention, grid, window, context):
            out = originals["native_local"](attention, grid, window, context)
            return record("native", out) if getattr(attention, "_experiment_stats", None) is handle else out
        def adaptive_capture(attention, grid, target, context):
            out = originals["adaptive_local"](attention, grid, target, context)
            if getattr(attention, "_experiment_stats", None) is handle:
                return record("adaptive", out[0]), out[1]
            return out
        def global_capture(attention, grid, context):
            out = originals["global_attention"](attention, grid, context)
            return record("global", out) if getattr(attention, "_experiment_stats", None) is handle else out
        if model_mod is not None:
            model_mod.native_local, model_mod.adaptive_local, model_mod.global_attention = native_capture, adaptive_capture, global_capture

    for index, module in enumerate(transformer.modules()):
        if not hasattr(module, "local_fusion") or not hasattr(module, "global_fusion"):
            continue
        if spec.native_local_weight is not None or spec.local_weight_bias is not None:
            value = spec.native_local_weight if spec.native_local_weight is not None else spec.local_weight_bias
            parameter = module.local_fusion.beta
            handle.parameters.append((parameter, parameter.detach().clone()))
            with torch.no_grad():
                parameter.add_(_logit(value) - _logit(0.5))
        if spec.reduce_global_to_local_weight is not None:
            parameter = module.global_fusion.beta
            handle.parameters.append((parameter, parameter.detach().clone()))
            with torch.no_grad():
                parameter.add_(_logit(spec.reduce_global_to_local_weight) - _logit(0.5))
        if spec.collect_branch_stats and (marked is None or model_mod is None):
            def capture(_module, _inputs, output, *, block=index):
                tensor = output[0] if isinstance(output, tuple) else output
                if torch.is_tensor(tensor):
                    bucket = handle.stats.setdefault(block, {"sum": None, "energy": None, "spatial_gradient": None, "temporal_gradient": None, "count": 0})
                    value = tensor.detach().mean()
                    bucket["sum"] = value if bucket["sum"] is None else bucket["sum"] + value
                    bucket["count"] += 1
            handle.hook_handles.append(module.register_forward_hook(capture))
    return handle


def summarize(handle: InterventionHandle) -> dict[int, dict[str, float]]:
    """Materialize one scalar per block, intentionally syncing only here."""
    result = {}
    for branch, bucket in handle.stats.items():
        if not bucket["count"]:
            continue
        result[branch] = {key: float((bucket[key] / bucket["count"]).cpu())
                          for key in ("sum", "energy", "spatial_gradient", "temporal_gradient")
                          if bucket[key] is not None}
        result[branch]["count"] = bucket["count"]
    return result


__all__ = ["ExperimentSpec", "InterventionHandle", "install", "summarize"]
